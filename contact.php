<script>
function isValidEmail(email) {
    let res = /^\w+([\.-]?\w+)*@\w+([\.-]?\w+)*(\.\w+)+$/;
    return res.test(email);
}


function validateName() {
    $error = false;
    $value = $("#fullName").val().trim();

    if ($value == "") {
        $("#fullNameErr").show();
        $error = true;
    } else {
        $("#fullNameErr").hide();
    }
    return $error;
}

function validateCompanyName() {
    $error = false;
    $value = $("#companyName").val().trim();

    if ($value == "") {
        $("#companyNameErr").show();
        $error = true;
    } else {
        $("#companyNameErr").hide();
    }
    return $error;
}

function validateEmail() {
    $error = false;
    $value = $("#email").val().trim();

    if ($value == "" || !isValidEmail($value)) {
        $("#emailErr").show();
        $error = true;
    } else {
        $("#emailErr").hide();
    }
    return $error;
}

function validatePhone() {
    $error = false;
    $value = $("#phoneno").val().trim();

    if ($value == "" || $value.length != 10) {
        $("#phonenoErr").show();
        $error = true;
    } else {
        $("#phonenoErr").hide();
    }
    return $error;
}

function validateMessage() {
    $error = false;
    $value = $("#message").val().trim();

    if ($value == "" || $value.length < 10) {
        $("#messageErr").show();
        $error = true;
    } else {
        $("#messageErr").hide();
    }
    return $error;
}

function validateCaptcha() {
    $error = false;
    $value = $("#g-recaptcha-response").val().trim();
    console.log(">>>" + $value);

    if ($value == "" || $value.length < 10) {
        $("#captchaErr").show();
        $error = true;
    } else {
        $("#captchaErr").hide();
    }
    return $error;
}



function submitForm() {

    $("#sendBtn").css("pointer-events", "none");
    $("#sendBtn").addClass("disabledBtn");

    $error1 = validateName();
    $error2 = validateCompanyName();
    $error3 = validateEmail();
    $error4 = validatePhone();
    $error5 = validateMessage();
    $error6 = validateCaptcha();

    $error = $error1 || $error2 || $error3 || $error4 || $error5 || $error6;


    if (!$error) {

        var form = new FormData();
        form.append("fullName", $("#fullName").val().trim());
        form.append("companyName", $("#companyName").val().trim());
        form.append("email", $("#email").val().trim());
        form.append("phonecode", $("#phonecode").val().trim());
        form.append("phoneno", $("#phoneno").val().trim());
        form.append("productDetails", $("#productDetails").val().trim());
        form.append("message", $("#message").val().trim());
        form.append("captcha", $("#g-recaptcha-response").val().trim());

        var settings = {
            "url": "api/contact-form.php",
            "method": "POST",
            "timeout": 0,
            "processData": false,
            "mimeType": "multipart/form-data",
            "contentType": false,
            "data": form
        };

        $.ajax(settings).done(function(response) {
            $("#sendBtn").css("pointer-events", "auto");
            $("#sendBtn").removeClass("disabledBtn");
            console.log(response);
            var json = $.parseJSON(response);
            console.log(json.message);
            if (json.status == "success") {
                $("#response").html(json.message);
                $("#fullName").val("");
                $("#companyName").val("");
                $("#email").val("");
                $("#phoneno").val("");
                $("#message").val("");
            } else {
                $("#response").html(json.message);

            }

        });



    } else {
        $("#sendBtn").css("pointer-events", "auto");
        $("#sendBtn").removeClass("disabledBtn");
    }
}


